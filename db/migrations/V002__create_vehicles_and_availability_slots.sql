
-- Task 7: Vehicle Availability and Slot Management
-- PostgreSQL schema migration
-- Matches the Vehicle entity and existing database schema

CREATE TABLE IF NOT EXISTS vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_number VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL,
    capacity INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_vehicle_registration
        UNIQUE (vehicle_number),

    CONSTRAINT chk_vehicle_capacity
        CHECK (capacity > 0),

    CONSTRAINT chk_vehicle_type
        CHECK (type IN (
            'CAR', 'VAN', 'MINIBUS', 'BUS', 'TRUCK'
        ))
);

CREATE TABLE IF NOT EXISTS availability_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    available_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',

    CONSTRAINT fk_slot_vehicle
        FOREIGN KEY (vehicle_id)
        REFERENCES vehicles(id),

    CONSTRAINT chk_slot_time
        CHECK (end_time > start_time),

    CONSTRAINT chk_slot_status
        CHECK (status IN (
            'AVAILABLE', 'BOOKED', 'UNAVAILABLE'
        ))
);

CREATE INDEX IF NOT EXISTS idx_slot_date_status
    ON availability_slots (available_date, status);
